package com.cookquest.common.exception;

public enum ErrorCode {

    // ==========================================
    // --- Загальні помилки (Common) ---
    // ==========================================
    INTERNAL_SERVER_ERROR,                      // Непередбачувана внутрішня помилка сервера
    INTERNAL_ERROR,                             // Загальна внутрішня помилка (аліас)
    INVALID_REQUEST,                            // Загальна помилка некоректного запиту (Bad Request)
    VALIDATION_ERROR,                           // Помилка валідації вхідних даних (DTO)
    NOT_FOUND,                                  // Загальна помилка "сутності не знайдено"
    UNSUPPORTED_LANGUAGE,                       // Фронтенд надіслав мову, якої ми не знаємо (не 'uk' і не 'en')

    // ==========================================
    // --- Модуль Auth & Security (Авторизація) ---
    // ==========================================
    USER_NOT_FOUND,                             // Користувача, якого шукають або авторизують, не існує
    EMAIL_ALREADY_EXISTS,                       // Користувач з таким email вже зареєстрований
    USERNAME_ALREADY_EXISTS,                    // Користувач з таким іменем вже зареєстрований
    BAD_CREDENTIALS,                            // Неправильний email або пароль при вході
    INVALID_PRINCIPAL_TYPE,                     // Системна помилка Spring Security під час логіну
    UNAUTHORIZED_ACCESS,                        // Спроба отримати доступ до захищеного методу без токена
    STARTER_MASCOT_NOT_FOUND,                   // В БД не додано стартового маскота (MASCOT_BROCCOLI)

    // ==========================================
    // --- Модуль Profile (Профіль) ---
    // ==========================================
    PROFILE_NOT_FOUND,                          // Профіль користувача не знайдено
    LEVELS_NOT_CONFIGURED,                      // В базі даних не заповнена таблиця рівнів (levels). Гравець не може отримати рівень

    // ==========================================
    // --- Модуль Social (Друзі) ---
    // ==========================================
    CANNOT_ADD_SELF,                            // Юзер намагається додати в друзі сам себе
    FRIENDSHIP_ALREADY_EXISTS,                  // Вони вже друзі, або запит вже висить у когось із них
    FRIEND_REQUEST_NOT_FOUND,                   // Запит, який намагаються прийняти/відхилити, не знайдено (його вже відхилили)
    NOT_REQUEST_RECEIVER,                       // Юзер намагається прийняти запит, який відправили не йому
    FRIEND_REQUEST_ALREADY_PROCESSED,           // Запит вже був прийнятий раніше
    NOT_INVOLVED_IN_REQUEST,                    // Юзер намагається видалити запит, до якого не має відношення

    // ==========================================
    // --- Модуль Recipe (Рецепти) ---
    // ==========================================
    RECIPE_NOT_FOUND,                           // Рецепт не знайдено в базі даних
    RECIPE_PARSE_ERROR,                         // Рецепт є в базі, але його JSON пошкоджено (фронтенд може показати "Рецепт пошкоджено")

    // ==========================================
    // --- Модуль AI (Штучний інтелект) ---
    // ==========================================
    AI_GENERATION_FAILED,                       // Загальна помилка: збій під час звернення до текстового ШІ
    AI_VISION_FAILED,                           // Загальна помилка: ШІ не зміг обробити зображення
    PROFANITY_OR_UNSAFE_CONTENT,                // Спрацював цензурний фільтр (юзер ввів щось погане в запиті рецепта)
    NO_PHOTOS_PROVIDED,                         // Юзер не прикріпив жодного фото для розпізнавання
    TOO_MANY_PHOTOS,                            // Юзер завантажив більше ніж 3 фото
    AI_INVALID_RECIPE_FORMAT,                   // API Groq відповіло, але ми не змогли прочитати JSON
    AI_RECIPE_GENERATION_FAILED,                // ШІ не зміг придумати рецепт з наданих інгредієнтів
    AI_INGREDIENT_RECOGNITION_FAILED,           // ШІ дивиться на фото, але не бачить там їжі (може юзер сфоткав стіну)

    // ==========================================
    // --- Модуль Economy & Mascot (Магазин і Маскоти) ---
    // ==========================================
    INSUFFICIENT_COINS,                         // У юзера не вистачає грошей на покупку або генерацію
    MASCOT_NOT_FOUND,                           // Маскота не існує в базі
    MASCOT_NOT_FOR_SALE,                        // Юзер намагається купити кастомного або унікального маскота, який не продається
    MASCOT_ALREADY_OWNED,                       // Юзер намагається купити маскота, який в нього вже є
    MASCOT_NOT_OWNED,                           // Юзер намагається екіпірувати маскота, якого ще не купив
    MASCOT_GENERATION_FAILED,                   // API генерації картинок (Stability/Cloudinary) повернуло помилку

    // ==========================================
    // --- Модуль Quest (Квести) ---
    // ==========================================
    INVALID_WEEK_START_DATE,                    // Адмін намагається створити тиждень не з понеділка
    DAY_NOT_FOUND,                              // Вказаного дня не існує в базі
    QUEST_NOT_FOUND,                            // Квесту не існує в базі

    // ==========================================
    // --- Модуль Cooking (Готування) ---
    // ==========================================
    BATCH_ALREADY_USED,                         // Юзер вже почав готувати інший рецепт з цієї ж генерації (батчу)
    STEP_VERIFICATION_NOT_ALLOWED_IN_VIEW_MODE, // Спроба відправити фото в режимі "Тільки перегляд"
    INVALID_STEP_NUMBER,                        // Вказано неіснуючий крок рецепта
    PHOTO_ONLY_ALLOWED_ON_FINAL_STEP,           // У спрощеному режимі фото можна слати тільки на останній крок
    STEP_ALREADY_VERIFIED,                      // Цей крок вже був успішно пройдений
    SESSION_NOT_FOUND,                          // Сесії готування не існує
    NOT_SESSION_OWNER,                          // Спроба отримати доступ до чужої сесії готування
    SESSION_NOT_ACTIVE,                         // Сесія готування вже завершена або скасована

    // ==========================================
    // --- Модуль Battle (Битви) ---
    // ==========================================
    CANNOT_BATTLE_SELF,                         // Спроба викликати на батл самого себе
    RECIPE_NOT_VALID_FOR_BATTLE,                // Цей рецепт (наприклад, адмінський) не можна використовувати для битв
    RECIPE_ALREADY_USED_IN_BATTLE,              // Цей згенерований рецепт вже був використаний у битві або просто приготований
    BATTLE_NOT_FOUND,                           // Битву не знайдено за ID
    BATTLE_CANNOT_BE_ACCEPTED,                  // Битву вже неможливо прийняти (скасована, завершена або вже почалася)
    NOT_BATTLE_PARTICIPANT,                     // Юзер намагається прийняти/здати битву, в якій не бере участі
    BATTLE_ALREADY_ACCEPTED,                    // Юзер вже натиснув "Прийняти" і має активну сесію
    BATTLE_ALREADY_FINISHED,                    // Спроба здати результат битви, яка вже завершилася
    OPPONENT_NOT_FOUND,                         // Системна помилка: не вдалося знайти суперника в батлі

    // ==========================================
    // --- Модуль Infrastructure (Інфраструктура) ---
    // ==========================================
    EXTERNAL_API_ERROR,                         // Загальна помилка при зверненні до зовнішніх сервісів
    CLOUD_STORAGE_ERROR                         // Помилка завантаження файлу в Cloudinary (проблеми з мережею або лімітами)
}